class GenericSignalAdapter(BaseAdapter):
    def harmonize(self) -> AdapterResult:
        aliases = load_aliases()
        rows: list[pd.DataFrame] = []
        warnings: list[str] = []
        for path in self.discover((".csv", ".txt", ".parquet", ".json")):
            try:
                if path.suffix.lower() == ".parquet":
                    raw = pd.read_parquet(path)
                elif path.suffix.lower() == ".json":
                    raw = pd.read_json(path, lines=True)
                else:
                    raw = pd.read_csv(path, low_memory=False)
            except Exception as exc:
                warnings.append(f"Could not read {path.name}: {exc}")
                continue
            out = pd.DataFrame(index=raw.index)
            for field in [
                "technology", "timestamp_utc", "rssi_dbm", "snr_db", "rsrp_dbm",
                "rsrq_db", "sinr_db", "latitude", "longitude", "latency_ms",
                "payload_bytes", "retries", "delivery_success", "operator",
                "application_protocol",
            ]:
                column = find_column(raw.columns, field, aliases)
                if column is not None:
                    out[field] = raw[column]
            for field in ["rssi_dbm", "snr_db", "rsrp_dbm", "rsrq_db", "sinr_db", "latitude", "longitude", "latency_ms", "payload_bytes", "retries"]:
                if field in out:
                    out[field] = numeric(out[field])
            base = self.base_fields(path)
            for key, value in base.items():
                if key not in out:
                    out[key] = value
            out["observation_id"] = [f"{self.record['id']}:{path.stem}:{i}" for i in raw.index]
            rows.append(out)
        if not rows:
            return AdapterResult(self.finalise(pd.DataFrame()), warnings + ["No readable signal files found"])
        return AdapterResult(self.finalise(pd.concat(rows, ignore_index=True)), warnings)


class GenericPowerAdapter(BaseAdapter):
    skiprows = 0

    def harmonize(self) -> AdapterResult:
        aliases = load_aliases()
        rows: list[dict[str, object]] = []
        warnings: list[str] = []
        for path in self.discover((".csv", ".txt")):
            try:
                raw = pd.read_csv(path, skiprows=self.skiprows, low_memory=False)
            except Exception as exc:
                warnings.append(f"Could not read {path.name}: {exc}")
                continue
            time_col = find_column(raw.columns, "time_s", aliases)
            current_col = find_column(raw.columns, "current_a", aliases)
            current_ma_col = find_column(raw.columns, "current_ma", aliases)
            voltage_col = find_column(raw.columns, "voltage_v", aliases)
            power_col = find_column(raw.columns, "power_w", aliases)
            energy_col = find_column(raw.columns, "energy_j", aliases)
            energy_mj_col = find_column(raw.columns, "energy_mj", aliases)

            base = self.base_fields(path)
            row: dict[str, object] = dict(base)
            row["observation_id"] = f"{self.record['id']}:{path.stem}"
            row["notes"] = "Trace-level summary generated by STACKWISE"
            if time_col and (current_col or current_ma_col or power_col):
                current = raw[current_col] if current_col else numeric(raw[current_ma_col]) / 1000.0
                voltage: pd.Series | float | None = raw[voltage_col] if voltage_col else None
                if voltage is None and self.record.get("assumed_voltage_v") is not None:
                    voltage = float(self.record["assumed_voltage_v"])
                    row["notes"] = "Energy uses explicit registry voltage assumption"
                summary = integrate_trace(
                    raw[time_col],
                    current_a=current,
                    power_w=raw[power_col] if power_col else None,
                    voltage_v=voltage,
                )
                row.update(summary)
                if voltage_col:
                    row["voltage_v"] = float(numeric(raw[voltage_col]).median())
                elif np.isscalar(voltage) and voltage is not None:
                    row["voltage_v"] = float(voltage)
                if current is not None:
                    row["current_a"] = float(numeric(current).mean())
            elif energy_col or energy_mj_col:
                values = numeric(raw[energy_col]) if energy_col else numeric(raw[energy_mj_col]) / 1000.0
                row["energy_j"] = float(values.mean())
                row["sample_count"] = int(values.notna().sum())
                row["notes"] = "Mean of source-provided energy values"
            else:
                warnings.append(f"No recognised power/energy columns in {path.name}")
                continue
            rows.append(row)
        return AdapterResult(self.finalise(pd.DataFrame(rows)), warnings)


class WideBleRssiAdapter(BaseAdapter):
    def harmonize(self) -> AdapterResult:
        rows: list[pd.DataFrame] = []
        warnings: list[str] = []
        for path in self.discover((".csv", ".txt")):
            try:
                raw = pd.read_csv(path, low_memory=False)
            except Exception as exc:
                warnings.append(f"Could not read {path.name}: {exc}")
                continue
            rssi_columns = [
                column for column in raw.columns
                if column.casefold().startswith(("b", "beacon", "rssi"))
                and pd.api.types.is_numeric_dtype(raw[column])
            ]
            if not rssi_columns:
                warnings.append(f"No wide RSSI columns detected in {path.name}")
                continue
            id_columns = [c for c in raw.columns if c not in rssi_columns]
            long = raw.melt(id_vars=id_columns, value_vars=rssi_columns, var_name="radio_module", value_name="rssi_dbm")
            long["rssi_dbm"] = numeric(long["rssi_dbm"]).replace(-200, np.nan)
            base = self.base_fields(path, "BLE")
            for key, value in base.items():
                long[key] = value
            long["observation_id"] = [f"{self.record['id']}:{path.stem}:{i}" for i in long.index]
            rows.append(long)
        return AdapterResult(self.finalise(pd.concat(rows, ignore_index=True) if rows else pd.DataFrame()), warnings)
